// ─── opencc 简→日新字体转换器（懒加载） ─────────────────────────────────
let s2jConverter: ((s: string) => string) | null = null;
function getS2jConverter(): (s: string) => string {
  if (!s2jConverter) {
    // cn: 简体中文 → jp: 日文新字体（汉字层面，不处理假名/々）
    s2jConverter = OpenCC.Converter({ from: 'cn', to: 'jp' });
  }
  return s2jConverter;
}

const normalizeKey = (s: string): string => s.replace(/\s+/g, '').toLowerCase();

/**
 * 归一化女优搜索关键词为 minnano-av 可搜索的日文名。
 * 映射表命中 → 日文原名；否则 opencc 简→日转换；异常时原文透传。
 */
export function normalizeActressKeyword(input: string): string {
  const raw = input.trim();
  if (!raw) return raw;

  // 1. 映射表精确命中
  const mapped = ACTRESS_NAME_MAP[normalizeKey(raw)];
  if (mapped) return mapped;

  // 2. opencc 简→日新字体转换（纯汉字名兜底）
  try {
    return getS2jConverter()(raw);
  } catch {
    // 3. 转换异常时原文透传（用户可能已输日文/罗马音）
    return raw;
  }
}
